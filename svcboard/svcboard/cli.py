"""svcboard command-line interface."""
from __future__ import annotations

import argparse
import json
import sys
from typing import List

from .core import Service, scan


def _render_table(services: List[Service]) -> str:
    rows = [
        f"{'PORT':<6}{'PROTO':<6}{'HOST':<16}{'PID':<8}{'PROCESS':<20}{'SERVICE':<10} COMMAND",
        "-" * 78,
    ]
    for s in services:
        rows.append(
            f"{s.port:<6}{s.proto:<6}{s.host:<16}{str(s.pid or '-'):<8}"
            f"{(s.name or '-')[:19]:<20}{(s.hint or '-'):<10} {s.cmdline or ''}"
        )
    return "\n".join(rows)


def _render_markdown(services: List[Service]) -> str:
    lines = [
        "# svcboard — local service map",
        "",
        f"_Generated by svcboard · {len(services)} listening port(s)_",
        "",
        "| Port | Proto | Host | PID | Process | Service | Command |",
        "|-----:|-------|------|----:|---------|---------|---------|",
    ]
    for s in services:
        cmd = (
            (s.cmdline or "")
            .replace("|", "\\|")
            .replace("`", "&#96;")
            .replace("\n", " ")
        )
        lines.append(
            f"| {s.port} | {s.proto} | {s.host} | {s.pid or '-'} "
            f"| {s.name or '-'} | {s.hint or '-'} | {cmd} |"
        )
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(
        prog="svcboard",
        description="Scan local listening ports and the processes that own them.",
    )
    fmt = p.add_mutually_exclusive_group()
    fmt.add_argument("--json", action="store_true", help="output JSON")
    fmt.add_argument("--md", "--markdown", dest="markdown", action="store_true",
                     help="output Markdown (great for pasting into a README)")
    p.add_argument("--port", type=int, help="show only this port")
    p.add_argument("--no-process", action="store_true", help="skip process lookup (faster)")
    p.add_argument("--version", action="store_true", help="show version and exit")
    args = p.parse_args(argv)

    if args.version:
        from . import __version__
        print(__version__)
        return 0

    services = scan(with_process=not args.no_process)
    if args.port is not None:
        services = [s for s in services if s.port == args.port]

    if args.json:
        print(json.dumps([s.to_dict() for s in services], indent=2, ensure_ascii=False))
    elif args.markdown:
        print(_render_markdown(services))
    else:
        if not services:
            print("No listening TCP ports found.")
            return 0
        print(_render_table(services))
    return 0


if __name__ == "__main__":
    sys.exit(main())
